# Generate the embedded assembly: compile the rewritten module image into the executable, with code going into the single executable segment __TEXT only (Apple ITMS-90999: only one segment with execute permission is allowed).
#   __TEXT,__dm<name>img  complete address layout: original text, a zero-filled hole for W, then the patch area
#   __DM<name>W,__img     RW source: [round16K(TEXT_END), PATCH_OFF), rest of ro + data + bss (relocations land only here)
# At run time the loader leaves both code ranges in their signed __TEXT addresses and replaces only the zero-filled hole with a copy-on-write mapping of W. This never creates executable memory or a second executable segment.
#   Modules with the patch area before the base (negative PATCH_OFF, see patch_nso.py FAR): W is [round16K(TEXT_END), FILE_IMAGE_LEN), x1 is the patch area after FILE_IMAGE_LEN in the file; bss and the key page are not in the executable
# Modules with a negative PATCH_OFF retain the older three-piece representation for now.
# Usage: gen_embed.py <build output dir> <output .S> <module name...>; link flags are printed to stdout (-segprot for the W segment)
import os, sys
out, dst, names = sys.argv[1], sys.argv[2], sys.argv[3:]
PG = 0x4000
def r16(x): return (x + PG - 1) & ~(PG - 1)
asm = ['// Generated by dm/ios/tools/gen_embed.py; do not edit']
flags = ['-Wl,-segprot,__TEXT,rwx,rx']
for n in names:
    hdr = dict(l[2:].split() for l in open(f'{out}/{n}.fixups.tsv'))
    te, po = int(hdr['TEXT_END'], 16), int(hdr['PATCH_OFF'], 16)
    ko, ks = int(hdr['KEY_PAGE_OFF'], 16), int(hdr['KEY_PAGE_SIZE'], 16)
    bin_ = os.path.abspath(f'{out}/{n}.patched.bin'); sz = os.path.getsize(bin_)
    a, end = r16(te), r16(sz)
    if po < 0:   # patch area before the base (patch_nso.py FAR): keep the older remap representation
        fl = int(hdr['FILE_IMAGE_LEN'], 16)
        assert fl % PG == 0 and a <= fl and ko % PG == 0 and ks == PG and ko >= fl
        parts = ((f'__TEXT,__dm{n}x0', 0, a), (f'__DM{n}W,__img', a, fl), (f'__TEXT,__dm{n}x1', fl, end))
        for sect, lo, hi in parts:
            assert all(len(x) <= 16 for x in sect.split(',')[:2])
            fill = min(hi, sz) - lo
            asm += [f'    .section {sect}', '    .p2align 14', f'    .incbin "{bin_}", {lo:#x}, {fill:#x}']
            if hi - lo > fill: asm.append(f'    .space {hi - lo - fill:#x}')
            asm.append('    .p2align 14')
    else:
        assert po % PG == 0 and a <= ko and ko + ks <= po and ko % PG == 0 and ks == PG
        text_sect = f'__TEXT,__dm{n}img,regular,pure_instructions'
        assert len(text_sect.split(',')[1]) <= 16
        patch_fill = min(end, sz) - po
        asm += [f'    .section {text_sect}', '    .p2align 14',
                f'    .incbin "{bin_}", 0x0, {a:#x}', f'    .space {po - a:#x}',
                f'    .incbin "{bin_}", {po:#x}, {patch_fill:#x}']
        if end - po > patch_fill: asm.append(f'    .space {end - po - patch_fill:#x}')
        asm += ['    .p2align 14', f'    .section __DM{n}W,__img', '    .p2align 14',
                f'    .incbin "{bin_}", {a:#x}, {po - a:#x}', '    .p2align 14']
    flags.append(f'-Wl,-segprot,__DM{n}W,rw,rw')
tab = os.path.join(out, 'nro.tsv')
nros = [ln.split('\t')[0] for ln in open(tab) if ln.strip() and not ln.startswith('#') and not ln.startswith('refused\t')] if os.path.exists(tab) else []
if nros:
    at, rows = [0, 0, 0], []
    for i, sect in enumerate(('__TEXT,__dm_nro_x0', '__DM_NRO_W,__img', '__TEXT,__dm_nro_x1')):
        asm.append(f'    .section {sect}')
        for k, n in enumerate(nros):
            bin_, sz, parts = pieces(n); lo, hi = parts[i]
            if i == 0: rows.append([n])
            rows[k] += [at[i], hi - lo]; at[i] += hi - lo
            place(asm, bin_, sz, lo, hi)
    asm += ['    .section __DATA,__dm_nro_tab', '    .p2align 3']
    for r in rows:
        assert len(r[0]) < 32
        asm.append(f'    .ascii "{r[0]}"'); asm.append(f'    .space {32 - len(r[0])}')
        asm.append('    .quad ' + ', '.join(f'{v:#x}' for v in r[1:]))
    flags.append('-Wl,-segprot,__DM_NRO_W,rw,rw')
open(dst, 'w').write('\n'.join(asm) + '\n')
print(' '.join(flags))

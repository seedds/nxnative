#!/usr/bin/env python3
"""Prepare a per-game SwiftPM package that xtool can turn into an iOS app on Linux."""
import json
import os
from pathlib import Path
import plistlib
import shlex
import shutil
import sys


def swift_string(value):
    return json.dumps(str(value), ensure_ascii=False)


def xcconfig_values(path, name):
    for line in Path(path).read_text().splitlines():
        if line.startswith(name + " ="):
            return shlex.split(line.split("=", 1)[1].replace("$(inherited)", ""))
    return []


def package_manifest(core_sources, swift_sources, include_dirs, defines, frameworks, link_flags):
    cflags = [
        "-std=gnu11", "-O1", "-g", "-Wall", "-Wno-unused-function",
        "-fobjc-arc", "-mcpu=apple-a18", "-Dmain=dm_main", "-DDM_XTOOL=1",
    ]
    cflags.extend("-I" + d for d in include_dirs)
    cflags.extend(defines)
    settings = ",\n                ".join(swift_string(s) for s in cflags)
    frameworks_swift = ",\n                ".join(
        f".linkedFramework({swift_string(f)})" for f in frameworks
    )
    link_swift = ",\n                ".join(swift_string(f) for f in link_flags)
    core_list = ",\n                ".join(swift_string(s) for s in core_sources)
    app_list = ",\n                ".join(swift_string(s) for s in swift_sources)
    linker = []
    if frameworks_swift:
        linker.append(frameworks_swift)
    if link_swift:
        linker.append(f".unsafeFlags([{link_swift}])")
    linker_setting = ",\n            ".join(linker)
    return f'''// Generated by dm/ios/tools/xtool_project.py. Do not edit.
// swift-tools-version: 6.0
import PackageDescription

let package = Package(
    name: "DmIOS",
    platforms: [.iOS("26.0")],
    products: [.library(name: "DmIOS", targets: ["DmIOSApp"])],
    targets: [
        .target(
            name: "DmIOSCore",
            path: "Sources/DmIOSCore",
            sources: [{core_list}],
            publicHeadersPath: "include",
            cSettings: [.unsafeFlags([
                {settings}
            ])],
            linkerSettings: [{linker_setting}]
        ),
        .target(
            name: "DmIOSApp",
            dependencies: ["DmIOSCore"],
            path: "Sources/DmIOSApp",
            sources: [{app_list}]
        )
    ],
    swiftLanguageModes: [.v5]
)
'''


def write_info_plist(path):
    info = {
        "CFBundleExecutable": "DmIOS",
        "CFBundleDisplayName": os.environ["DM_DISPLAY_NAME"],
        "CFBundleName": os.environ["DM_DISPLAY_NAME"],
        "CFBundlePackageType": "APPL",
        "CFBundleVersion": os.environ["DM_APP_VERSION"],
        "CFBundleShortVersionString": os.environ["DM_APP_VERSION"],
        "MinimumOSVersion": "26.0",
        "LSRequiresIPhoneOS": True,
        "UIDeviceFamily": [1, 2],
        "UILaunchStoryboardName": "",
        "UIFileSharingEnabled": True,
        "LSSupportsOpeningDocumentsInPlace": True,
        "UISupportedInterfaceOrientations": [
            "UIInterfaceOrientationLandscapeRight",
            "UIInterfaceOrientationLandscapeLeft",
        ],
        "UIRequiresFullScreen": True,
        "UIStatusBarHidden": True,
        "UIViewControllerBasedStatusBarAppearance": False,
        "LSApplicationCategoryType": os.environ["DM_APP_CATEGORY"],
        "DMShowFPS": os.environ.get("DM_SHOW_FPS", "NO") == "YES",
        "DMLanguage": os.environ.get("DM_LANG", "en-US"),
        "LSSupportsGameMode": True,
        "GCSupportsControllerUserInteraction": True,
        "GCSupportedGameControllers": [{"ProfileName": "ExtendedGamepad"}],
        "CADisableMinimumFrameDurationOnPhone": True,
        "UIApplicationSceneManifest": {
            "UIApplicationSupportsMultipleScenes": False,
            "UISceneConfigurations": {
                "UIWindowSceneSessionRoleApplication": [{
                    "UISceneConfigurationName": "Default",
                    "UISceneDelegateClassName": "SceneDelegate",
                }],
            },
        },
    }
    if os.environ.get("DM_METAL_CAPTURE") == "1":
        info["MetalCaptureEnabled"] = True
    path.write_bytes(plistlib.dumps(info, fmt=plistlib.FMT_XML, sort_keys=False))


def write_entitlements(package, ios):
    setting = os.environ.get("DM_ENTITLEMENTS", "__default__")
    if setting == "":
        return None
    destination = package / "DmIOS.entitlements"
    if setting == "__default__":
        text = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
            '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
            '<plist version="1.0"><dict><key>'
            'com.apple.developer.kernel.increased-memory-limit'
            '</key><true/></dict></plist>\n'
        )
        destination.write_text(text, encoding="utf-8")
    else:
        source = Path(setting).expanduser().resolve()
        if not source.is_file():
            raise SystemExit(f"DM_ENTITLEMENTS does not exist: {source}")
        shutil.copy2(source, destination)
    return destination.name


def copy_sources(package, ios, gen):
    core = package / "Sources/DmIOSCore"
    include = core / "include"
    app = package / "Sources/DmIOSApp"
    for directory in (core, include, app):
        shutil.rmtree(directory, ignore_errors=True)
        directory.mkdir(parents=True, exist_ok=True)

    core_sources = []
    for source in sorted((gen / "src").iterdir()):
        if not source.is_file():
            continue
        target = core / source.name
        shutil.copy2(source.resolve(), target)
        core_sources.append(target.name)

    for relative in ("main/main.c", "embed.S"):
        source = gen / relative
        if not source.is_file():
            raise SystemExit(f"missing generated iOS source: {source}")
        target = core / source.name
        shutil.copy2(source.resolve(), target)
        core_sources.append(target.name)

    for source in sorted((ios / "Sources").iterdir()):
        if source.is_file() and source.suffix in (".m", ".h"):
            target = core / source.name
            shutil.copy2(source, target)
            if source.suffix == ".m":
                core_sources.append(target.name)

    public_header = ios / "Sources/include/DmIOSApp.h"
    if not public_header.is_file():
        raise SystemExit(f"missing SwiftPM bridging header: {public_header}")
    shutil.copy2(public_header, include / public_header.name)

    swift_sources = []
    for name in ("Launcher.swift", "LauncherRow.swift", "LauncherSettings.swift", "NxNativeEntry.swift"):
        source = ios / "Sources" / name
        if not source.is_file():
            raise SystemExit(f"missing Swift iOS source: {source}")
        shutil.copy2(source, app / name)
        swift_sources.append(name)
    return core_sources, swift_sources


def main():
    if len(sys.argv) != 5:
        raise SystemExit("usage: xtool_project.py <package dir> <dm/ios source dir> <Gen dir> <product name>")
    package, ios, gen = map(lambda p: Path(p).resolve(), sys.argv[1:4])
    product = sys.argv[4]
    package.mkdir(parents=True, exist_ok=True)
    config = gen / "dm.xcconfig"
    if not config.is_file():
        raise SystemExit(f"missing generated iOS build settings: {config}")

    core_sources, swift_sources = copy_sources(package, ios, gen)
    include_dirs = [p for p in xcconfig_values(config, "HEADER_SEARCH_PATHS") if not p.startswith("$(")]
    include_dirs = [p for p in include_dirs if p and p != "inherited"]
    defines = [p for p in xcconfig_values(config, "OTHER_CFLAGS") if p.startswith("-D")]
    framework_tokens = xcconfig_values(config, "DM_FRAMEWORKS")
    frameworks = []
    for index, token in enumerate(framework_tokens[:-1]):
        if token == "-framework" and framework_tokens[index + 1] != "Cocoa":
            frameworks.append(framework_tokens[index + 1])
    link_tokens = xcconfig_values(config, "OTHER_LDFLAGS")
    link_flags = []
    skip_framework = False
    for token in link_tokens:
        if token in ("-framework", "$(inherited)", "$(DM_FRAMEWORKS)"):
            skip_framework = token == "-framework"
            continue
        if skip_framework:
            skip_framework = False
            continue
        if not token.startswith("$("):
            link_flags.append(token)

    (package / "Package.swift").write_text(
        package_manifest(core_sources, swift_sources, include_dirs, defines, frameworks, link_flags),
        encoding="utf-8",
    )
    write_info_plist(package / "Info.plist")
    entitlement_path = write_entitlements(package, ios)
    icon_source = gen / "Assets.xcassets/AppIcon.appiconset/icon.png"
    icon_path = None
    if icon_source.is_file():
        shutil.copy2(icon_source, package / "AppIcon.png")
        icon_path = "AppIcon.png"
    config_lines = [
        "version: 1",
        f"bundleID: {json.dumps(os.environ['DM_BUNDLE_ID'])}",
        f"product: {json.dumps(product)}",
        'infoPath: "Info.plist"',
        "skipLSP: true",
    ]
    if icon_path:
        config_lines.append(f"iconPath: {json.dumps(icon_path)}")
    if entitlement_path:
        config_lines.append(f"entitlementsPath: {json.dumps(entitlement_path)}")
    (package / "xtool.yml").write_text("\n".join(config_lines) + "\n", encoding="utf-8")
    print(f"xtool SwiftPM package: {package}")


if __name__ == "__main__":
    main()

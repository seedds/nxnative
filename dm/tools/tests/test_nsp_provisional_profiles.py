# A provisional profile found by title ID outside dm/games (build_ipa_from_nsp.py provisional_profile): the second build of a multi-program game finds its other programs'
# provisional profiles through DM_GAMES_DIR, and packs them as provisional ones, so a split that now reads more files updates their tables instead of stopping
import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest

REPO = Path(__file__).resolve().parents[3]
spec = importlib.util.spec_from_file_location('build_ipa_from_nsp', REPO / 'scripts/build_ipa_from_nsp.py')
assert spec and spec.loader
nsp = importlib.util.module_from_spec(spec); spec.loader.exec_module(nsp)
sys.path.insert(0, str(REPO / 'dm/games'))
import game as gamemod  # noqa: E402


class ProvisionalProfile(unittest.TestCase):
    def profile(self, root, tid, head):
        d = Path(root) / tid; d.mkdir(parents=True)
        (d / 'game.tsv').write_text(f'{head}\n\ntitle_id\t{tid}\nprogram_id\t{tid}\nprogram_of\t010049900F546000\n', encoding='utf-8')
        return gamemod.load(str(d))

    def test_written_provisional_outside_dm_games(self):
        with tempfile.TemporaryDirectory() as t:
            g = self.profile(t, '010049900F546001', nsp.PROVISIONAL_HEAD + ' (generated by scripts/build_ipa_from_nsp.py …)')
            self.assertTrue(nsp.provisional_profile(g, gamemod.HERE))

    def test_hand_made_profile_outside_dm_games(self):   # a profile kept in DM_GAMES_DIR that the script did not write as provisional stays registered
        with tempfile.TemporaryDirectory() as t:
            g = self.profile(t, '010049900F546001', '# Super Mario 3D All-Stars: Super Mario 64')
            self.assertFalse(nsp.provisional_profile(g, gamemod.HERE))

    def test_profile_in_dm_games(self):   # moved into dm/games, a profile is registered whatever its first line says
        with tempfile.TemporaryDirectory() as t:
            g = self.profile(t, '010049900F546001', nsp.PROVISIONAL_HEAD)
            self.assertFalse(nsp.provisional_profile(g, g.dir.parent))

    def test_written_header_starts_with_the_marker(self):   # write_profile and the check use one constant
        src = (REPO / 'scripts/build_ipa_from_nsp.py').read_text(encoding='utf-8')
        self.assertIn("L = [PROVISIONAL_HEAD + ' (generated by", src)


if __name__ == '__main__':
    unittest.main()
